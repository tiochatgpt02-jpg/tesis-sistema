#!/usr/bin/env python3
"""Rebuild the live users table to the schema expected by the app."""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv

load_dotenv(ROOT / '.env')

import psycopg


DB_HOST = os.getenv('POSTGRES_HOST', 'localhost')
DB_PORT = int(os.getenv('POSTGRES_PORT', '5432'))
DB_NAME = os.getenv('POSTGRES_DB', 'sistema_ia')
DB_USER = os.getenv('POSTGRES_USER', 'postgres')
DB_PASSWORD = os.getenv('POSTGRES_PASSWORD', '')


def connect():
    return psycopg.connect(
        host=DB_HOST,
        port=DB_PORT,
        user=DB_USER,
        password=DB_PASSWORD,
        dbname=DB_NAME,
    )


def legacy_role_to_app(rol):
    value = str(rol or '').strip().lower()
    if value in {'profesor', 'teacher', 'admin'}:
        return 'teacher'
    return 'student'


def legacy_grade_to_int(grado):
    value = str(grado or '').strip().lower()
    if value == '4to':
        return 4
    if value == '5to':
        return 5
    if value == '6to':
        return 6
    return None


def rebuild_users_table(cur):
    cur.execute("SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'users'")
    if not cur.fetchone():
        cur.execute(
            """
            CREATE TABLE users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                role VARCHAR(30) NOT NULL,
                first_name VARCHAR(100) NOT NULL DEFAULT '',
                last_name VARCHAR(100) NOT NULL DEFAULT '',
                email VARCHAR(255) NOT NULL DEFAULT '',
                phone VARCHAR(30),
                grade INTEGER,
                student_id BIGINT,
                section VARCHAR(10) DEFAULT 'A',
                two_step_code VARCHAR(10),
                two_step_expires TIMESTAMP,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        return

    cur.execute("SELECT 1 FROM information_schema.columns WHERE table_name = 'users' AND column_name = 'password_hash'")
    has_new_columns = cur.fetchone() is not None
    if has_new_columns:
        return

    cur.execute("ALTER TABLE users RENAME TO users_legacy")
    cur.execute(
        """
        CREATE TABLE users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR(100) NOT NULL UNIQUE,
            password_hash VARCHAR(255) NOT NULL,
            role VARCHAR(30) NOT NULL,
            first_name VARCHAR(100) NOT NULL DEFAULT '',
            last_name VARCHAR(100) NOT NULL DEFAULT '',
            email VARCHAR(255) NOT NULL DEFAULT '',
            phone VARCHAR(30),
            grade INTEGER,
            student_id BIGINT,
            section VARCHAR(10) DEFAULT 'A',
            two_step_code VARCHAR(10),
            two_step_expires TIMESTAMP,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
        """
    )


def insert_legacy_users(cur):
    cur.execute(
        """
        INSERT INTO users (username, password_hash, role, first_name, last_name, email, grade, section)
        SELECT
            username,
            contrasena AS password_hash,
            CASE LOWER(COALESCE(rol, ''))
                WHEN 'estudiante' THEN 'student'
                WHEN 'student' THEN 'student'
                WHEN 'profesor' THEN 'teacher'
                WHEN 'teacher' THEN 'teacher'
                WHEN 'admin' THEN 'teacher'
                ELSE 'student'
            END AS role,
            split_part(COALESCE(nombre_completo, ''), ' ', 1) AS first_name,
            regexp_replace(COALESCE(nombre_completo, ''), '^[^ ]+\\s+', '') AS last_name,
            username || '@colegio.edu' AS email,
            CASE LOWER(COALESCE(grado, ''))
                WHEN '4to' THEN 4
                WHEN '5to' THEN 5
                WHEN '6to' THEN 6
                ELSE NULL
            END AS grade,
            'A' AS section
        FROM users_legacy
        ON CONFLICT (username) DO NOTHING
        """
    )


def main():
    with connect() as conn:
        with conn.cursor() as cur:
            rebuild_users_table(cur)
            if cur.execute("SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'users_legacy'").fetchone():
                insert_legacy_users(cur)
            conn.commit()

            cur.execute("SELECT username, role, grade, first_name, last_name, password_hash FROM users ORDER BY id LIMIT 10")
            print(cur.fetchall())
            cur.execute("SELECT role, COUNT(*) FROM users GROUP BY role ORDER BY role")
            print(cur.fetchall())

    print('Base de usuarios reconstruida y lista para login real.')


if __name__ == '__main__':
    main()
